#!/usr/bin/env bash
# Regenerate docs/CLI.md from the binaries' own --help output.
#
#   cargo build && scripts/gen-cli-docs.sh
#
# Run this whenever a command, flag or help text changes; CI fails if the file is stale.
set -euo pipefail

BIN=${BIN:-target/debug}
OUT=${OUT:-docs/CLI.md}
EXE=""
[ -x "$BIN/zknbe.exe" ] && EXE=".exe"

section() { # section <binary> <subcommand words...>
    local bin=$1; shift
    printf '\n### `%s`\n\n```text\n' "$bin${*:+ $*}"
    # Normalise the program name and line endings so output is identical on every OS.
    "$BIN/$bin$EXE" "$@" --help | tr -d '\r' | sed -e "s/$bin\.exe/$bin/g" -e 's/[[:space:]]*$//'
    printf '```\n'
}

{
    cat <<'HEADER'
# Command reference

<!-- Generated by scripts/gen-cli-docs.sh from --help output. Do not edit by hand. -->

Three binaries:

| Binary | Runs on | Purpose |
|---|---|---|
| [`zknbe`](#zknbe--device-client) | the machine being protected | bind volumes, unlock, heartbeat agent |
| [`zknbed`](#zknbed--key-server) | the key server | holds per-device keys, enforces policy |
| [`zknbectl`](#zknbectl--key-server-administration) | the key server (or via SSH tunnel) | tokens, devices, audit |

Durations accept `90`, `90s`, `15m`, `4h`, `7d`.

## `zknbe` — device client
HEADER
    section zknbe
    for sub in "luks" "luks bind" "luks open" "luks passphrase" "luks unbind" "luks status" \
               "enroll" "unlock" "status" "rotate" "agent" "tpm seal" "tpm unseal" "askpass"; do
        # shellcheck disable=SC2086
        section zknbe $sub
    done

    printf '\n## `zknbed` — key server\n'
    section zknbed

    printf '\n## `zknbectl` — key server administration\n'
    section zknbectl
    for sub in "status" "token create" "token list" "token delete" \
               "device list" "device show" "device approve" "device approve-all-locked" \
               "device suspend" "device resume" "device revoke" "device delete" "device policy" \
               "audit list" "audit verify"; do
        # shellcheck disable=SC2086
        section zknbectl $sub
    done
} > "$OUT"

echo "wrote $OUT"
